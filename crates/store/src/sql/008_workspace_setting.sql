-- 工作区设置：工作目录、权限档、上次环境检查时间。
--
-- 界面顶栏与侧栏一直显示着「尚未授权工作目录 / 未设置权限档 /
-- 环境尚未检查」三条提醒，而在此之前**没有任何东西能把它们改掉** ——
-- 那三处根本没有数据源。首次配置屏点什么按钮都不会变。
--
-- key-value 而不是固定列：设置会随功能长出新项（图纸的设置屏有 8 个分组），
-- 每加一项就改一次表结构不划算。键由 Rust 侧的白名单挡，
-- 不挡的话它会慢慢变成什么都往里塞的垃圾桶。
CREATE TABLE workspace_setting (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
